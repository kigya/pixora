#!/usr/bin/env python3
"""Prepare checksum-pinned ncnn CPU iOS SDK locally; never installs system software."""
from pathlib import Path
import hashlib, os, shutil, stat, subprocess, zipfile
ROOT=Path(__file__).resolve().parent.parent
SDK=ROOT/'.p-build-app/local/ios-sdk'
LOCK={
 'device':('https://github.com/Tencent/ncnn/releases/download/20260526/ncnn-20260526-ios.zip','4546a3e16f83fe9f4c6e9f3cb94037093ee03b7ff3ae8ee07b7533010f861e20'),
 'simulator':('https://github.com/Tencent/ncnn/releases/download/20260526/ncnn-20260526-ios-simulator.zip','ba4c9a44b39f8961dec5cdf870da2484278de12e9a14ef44564ba2dde8e7e488'),
}
SDK.mkdir(parents=True,exist_ok=True)
for platform,(url,expected) in LOCK.items():
 archive=SDK/(platform+'.zip')
 if not archive.is_file():subprocess.run(['curl','-fLsS','--retry','2',url,'-o',str(archive)],check=True)
 if hashlib.sha256(archive.read_bytes()).hexdigest()!=expected:raise SystemExit('ncnn checksum mismatch: '+platform)
 directory=SDK/platform
 if not directory.exists():
  directory.mkdir()
  with zipfile.ZipFile(archive) as contents:
   for entry in contents.infolist():
    path=Path(entry.filename)
    if path.is_absolute() or '..' in path.parts:raise SystemExit('Unsafe SDK archive path')
    target=directory/path
    if entry.is_dir():target.mkdir(parents=True,exist_ok=True);continue
    target.parent.mkdir(parents=True,exist_ok=True)
    if stat.S_ISLNK(entry.external_attr>>16):target.symlink_to(contents.read(entry).decode())
    else:target.write_bytes(contents.read(entry))
 for library in ('ncnn','openmp'):
  shutil.copyfile(directory/(library+'.framework')/library,directory/('lib'+library+'.a'))
 # Combine ncnn and its OpenMP runtime in one archive so CocoaPods does not
 # collide on two XCFrameworkIntermediates/<pod>/Headers directories.
 subprocess.run(['xcrun','libtool','-static','-o',str(directory/'libpixora_ncnn.a'),str(directory/'libncnn.a'),str(directory/'libopenmp.a')],check=True)
vendor=ROOT/'ios/Vendor';vendor.mkdir(exist_ok=True)
output=vendor/'ncnn.xcframework'
if not output.exists():
 command=['xcodebuild','-create-xcframework']
 for platform in LOCK:
  headers=(SDK/platform/'ncnn.framework/Headers/ncnn').resolve()
  command+=['-library',str(SDK/platform/'libpixora_ncnn.a'),'-headers',str(headers)]
 subprocess.run(command+['-output',str(output)],check=True)
# Keep feedback endpoint source local and generated bytes ignored. No URL is printed.
properties=ROOT/'android/feedback.properties'
if not properties.exists():
 supplied=os.environ.get('PIXORA_FEEDBACK_PROPERTIES')
 if supplied:properties=Path(supplied)
subprocess.run(['python3',str(ROOT/'scripts/encode-feedback-endpoint.py'),str(properties),str(ROOT/'ios/Native/feedback_endpoint.h')],check=True)
print('Pinned ncnn 20260526 CPU SDK and generated native configuration ready')
